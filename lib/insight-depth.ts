const NOINDEX = new Set(['nigeria-los-air-freight-customs-risk'])

export function applyInsightDepth(insight: SeoInsight): SeoInsight {
  const path = `/insights/${insight.slug}/`
  const expansion = insightExpansions[insight.slug]
  const historical = contentLastModified[path]
  const noindex = NOINDEX.has(insight.slug)
  const modifiedDate = expansion
    ? DEPTH_DATE
    : historical && historical !== insight.date
      ? historical
      : insight.modifiedDate

  if (!expansion && !noindex && modifiedDate === insight.modifiedDate) return insight

  const routes = expansion?.routes ?? []
  const seen = new Set(insight.relatedRoutes.map((route) => route.href.split('?')[0]))

  return {
    ...insight,
    noindex,
    modifiedDate,
    readTime: expansion?.readTime ?? insight.readTime,
    answerLead: expansion?.answer ?? (noindex
      ? '这篇是早期短稿，没有独立来源。尼日利亚 LOS 请改看 SONCAP / Form M / PAAR 和 B’Odogwu 两篇有来源的清关页。本页不再作为索引页。'
      : insight.answerLead),
    sections: expansion
      ? [...insight.sections, ...expansion.sections, ...(moreDepth[insight.slug] ? [moreDepth[insight.slug]] : [])]
      : insight.sections,
    faqs: expansion?.faqs ?? insight.faqs,
    relatedRoutes: [
      ...insight.relatedRoutes,
      ...routes.filter((route) => !seen.has(route.href.split('?')[0])),
    ],
  }
}
